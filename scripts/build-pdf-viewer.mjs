// Builds assets/pdf-viewer.html — the offline in-app textbook reader (#9).
//
// Android's WebView can't render PDFs, so the reader is PDF.js inlined into one
// HTML file the app ships as an asset. Pinned to 3.11.174 (last release with a
// classic, non-module build that loads from file://). Its CVE-2024-4367 is
// mitigated by `isEvalSupported: false` below.
//
// Run: node scripts/build-pdf-viewer.mjs
import { writeFileSync } from 'node:fs'

const VERSION = '3.11.174'
const base = `https://cdn.jsdelivr.net/npm/pdfjs-dist@${VERSION}/legacy/build`

async function get(file) {
  const res = await fetch(`${base}/${file}`)
  if (!res.ok) throw new Error(`${file}: HTTP ${res.status}`)
  const text = await res.text()
  if (/<\/script/i.test(text)) throw new Error(`${file} contains </script and can't be inlined`)
  return text
}

const [lib, worker] = await Promise.all([get('pdf.min.js'), get('pdf.worker.min.js')])

const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=5">
<!-- Generated by scripts/build-pdf-viewer.mjs from pdfjs-dist@${VERSION}. Do not edit by hand. -->
<style>
  html, body { margin: 0; background: #e5e7eb; font-family: -apple-system, Roboto, sans-serif; }
  #pages { display: flex; flex-direction: column; align-items: center; gap: 8px; padding: 8px 0 80px; }
  .page { width: calc(100% - 16px); background: #fff; box-shadow: 0 1px 3px rgba(0,0,0,.15); }
  .page canvas { display: block; width: 100%; height: 100%; }
  #bar { position: fixed; left: 12px; right: 12px; bottom: 12px; display: flex; align-items: center; gap: 12px;
    padding: 8px 16px; border-radius: 999px; background: rgba(17,24,39,.85); color: #fff; font-size: 13px; }
  #bar[hidden] { display: none; }
  #slider { flex: 1; height: 28px; accent-color: #14b8a6; }
  #counter { min-width: 64px; text-align: right; font-variant-numeric: tabular-nums; }
  #status { padding: 48px 24px; text-align: center; color: #4b5563; font-size: 15px; }
</style>
</head>
<body>
<div id="status">Opening book…</div>
<div id="pages"></div>
<div id="bar" hidden>
  <input id="slider" type="range" min="1" value="1" step="1" aria-label="Go to page">
  <span id="counter" aria-live="polite"></span>
</div>
<script type="text/plain" id="pdf-worker">${worker}</script>
<script>${lib}</script>
<script>
(async () => {
  const status = document.getElementById('status')
  const pagesEl = document.getElementById('pages')
  const bar = document.getElementById('bar')
  const slider = document.getElementById('slider')
  const counter = document.getElementById('counter')
  // The app opens viewer.html#<file>.pdf with the PDF saved next to it.
  const file = decodeURIComponent(location.hash.slice(1))
  if (!/^[\\w-]+\\.pdf$/.test(file)) { status.textContent = 'Book not found.'; return }

  // Worker from a blob so it runs off the main thread; PDF.js falls back to
  // the main thread by itself if the WebView refuses the worker.
  const workerBlob = new Blob([document.getElementById('pdf-worker').textContent], { type: 'text/javascript' })
  pdfjsLib.GlobalWorkerOptions.workerSrc = URL.createObjectURL(workerBlob)

  let pdf
  try {
    pdf = await pdfjsLib.getDocument({ url: file, isEvalSupported: false }).promise
  } catch (e) {
    status.textContent = "Couldn't open this book. Delete the download and try again."
    return
  }
  status.remove()
  // Right after a download the WebView can still be 0px wide while the screen
  // animates in; drawing then makes 0x0 canvases and blank pages.
  while (pagesEl.clientWidth === 0) await new Promise((r) => requestAnimationFrame(r))

  // Placeholders sized to each page's aspect ratio so scrolling is stable;
  // only pages near the screen hold a canvas.
  const first = await pdf.getPage(1)
  const vp1 = first.getViewport({ scale: 1 })
  const pages = []
  for (let n = 1; n <= pdf.numPages; n++) {
    const el = document.createElement('div')
    el.className = 'page'
    el.style.aspectRatio = vp1.width + ' / ' + vp1.height
    el.dataset.n = n
    pagesEl.appendChild(el)
    pages.push(el)
  }

  // ponytail: renders at 2x device pixels so pinch-zoom stays readable; re-render on zoom if that isn't sharp enough.
  const scaleFor = (page) => {
    const vp = page.getViewport({ scale: 1 })
    return (pagesEl.clientWidth - 16) / vp.width * Math.min(window.devicePixelRatio * 2, 4)
  }

  async function render(el) {
    if (el.firstChild) return
    const page = await pdf.getPage(Number(el.dataset.n))
    const vp = page.getViewport({ scale: scaleFor(page) })
    el.style.aspectRatio = vp.width + ' / ' + vp.height
    const canvas = document.createElement('canvas')
    canvas.width = vp.width
    canvas.height = vp.height
    el.appendChild(canvas)
    await page.render({ canvasContext: canvas.getContext('2d'), viewport: vp }).promise
  }

  function release(el) {
    const canvas = el.firstChild
    if (!canvas) return
    canvas.width = 0; canvas.height = 0 // frees the bitmap memory right away
    el.removeChild(canvas)
  }

  const io = new IntersectionObserver((entries) => {
    for (const e of entries) e.isIntersecting ? render(e.target).catch(() => {}) : release(e.target)
  }, { rootMargin: '150% 0px' })
  pages.forEach((el) => io.observe(el))

  let current = 1
  let dragging = false
  const label = (n) => { counter.textContent = n + ' / ' + pdf.numPages }
  const goTo = (n) => { current = n; window.scrollTo(0, pages[n - 1].offsetTop - 8) }

  window.addEventListener('scroll', () => {
    if (dragging) return
    const mid = window.scrollY + window.innerHeight / 2
    const el = pages.find((p) => p.offsetTop + p.offsetHeight > mid) || pages[pages.length - 1]
    current = Number(el.dataset.n)
    slider.value = current
    label(current)
  }, { passive: true })

  // Drag the slider to jump anywhere in the book.
  slider.max = pdf.numPages
  slider.addEventListener('input', () => { dragging = true; label(slider.value); goTo(Number(slider.value)) })
  slider.addEventListener('change', () => { dragging = false })

  // Rotating changes every page's height; keep the reader on the same page.
  let lastWidth = pagesEl.clientWidth
  window.addEventListener('resize', () => {
    if (pagesEl.clientWidth === lastWidth) return
    lastWidth = pagesEl.clientWidth
    const keep = current
    requestAnimationFrame(() => goTo(keep))
  })

  label(1)
  bar.hidden = false
})()
</script>
</body>
</html>
`

writeFileSync(new URL('../assets/pdf-viewer.html', import.meta.url), html)
console.log(`assets/pdf-viewer.html written (${(html.length / 1024 / 1024).toFixed(2)} MB, pdfjs-dist@${VERSION})`)
